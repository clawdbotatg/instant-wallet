import { chromium } from "playwright-core";
const out = process.argv[2];
const b = await chromium.launch({ executablePath: process.env.CHROME });
const p = await b.newPage({ viewport: { width: 420, height: 900 }, deviceScaleFactor: 2 });
await p.goto("https://instantwallet.io/?watch=0xd8dA6BF26964aF9D7eEd9e03E53415D37aA96045", { waitUntil: "domcontentloaded" });
await p.locator('[aria-label^="Send "]:not([aria-label="Send everything"]):not([aria-label="Send or scan"])').first().waitFor({ timeout: 60000 });
const row = p.locator('.asset[aria-label^="Send "]').first();
console.log("row:", await row.getAttribute("aria-label"));
await row.click();
await p.locator(".send-or-swap").waitFor({ timeout: 15000 });
await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/send.png` });
console.log("send pills:", await p.locator(".send-or-swap .pill").evaluateAll(els => els.map(e => `${e.textContent}${e.classList.contains("on") ? "*" : ""}`)));
await p.locator(".send-or-swap .pill", { hasText: "Swap" }).click();
await p.locator(".go-swap").waitFor({ timeout: 15000 });
await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/swap.png` });
console.log("swap pills:", await p.locator(".send-or-swap .pill").evaluateAll(els => els.map(e => `${e.textContent}${e.classList.contains("on") ? "*" : ""}`)));
console.log("swap from:", await p.locator(".swap .field").first().locator(".pill.select").first().innerText());
await p.locator(".send-or-swap .pill", { hasText: "Send" }).click();
await p.waitForTimeout(600);
console.log("back on send:", await p.locator(".send-or-swap .pill.on").innerText(), "| scanner:", await p.locator("video").count());
await b.close();
