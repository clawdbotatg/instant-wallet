/** digest: 0x-prefixed 32-byte hex -> "amber fox 42" */
export function matchCode(digest: `0x${string}`): string {
  const h = digest.slice(2);
  const b = (i: number) => parseInt(h.slice(i * 2, i * 2 + 2), 16);
  return `${MATCH_WORDS[b(0)]} ${MATCH_WORDS[b(1)]} ${b(2) % 100}`;
}
